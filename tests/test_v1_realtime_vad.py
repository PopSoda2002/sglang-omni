class FakeClient:
    def __init__(self, chunks_per_call: list[list[CompletionStreamChunk]]) -> None:
        self._chunks_per_call = list(chunks_per_call)
        self.calls = 0
        self.last_payloads: list[Any] = []
        self.aborted_ids: list[str] = []

    async def completion_stream(
        self, request: Any, *, request_id: str, audio_format: str = "wav"
    ) -> AsyncIterator[CompletionStreamChunk]:
        idx = self.calls
        self.calls += 1
        self.last_payloads.append(request.metadata.get("audios"))
        chunks = (
            self._chunks_per_call[idx]
            if idx < len(self._chunks_per_call)
            else self._chunks_per_call[-1]
        )
        for c in chunks:
            yield c

    async def abort(
        self, request_id: str, level: AbortLevel = AbortLevel.SOFT
    ) -> AbortResult:
        self.aborted_ids.append(request_id)
        return AbortResult(success=True, level_applied=level)

    def health(self) -> dict[str, Any]:
        return {"running": True}


def _read_wav_pcm16_16k(path: Path) -> bytes:
    with wave.open(str(path), "rb") as wf:
        assert wf.getframerate() == 16000
        assert wf.getsampwidth() == 2
        assert wf.getnchannels() == 1
        return wf.readframes(wf.getnframes())


def _b64(data: bytes) -> str:
    return base64.b64encode(data).decode("ascii")


def _silence_pcm(ms: int) -> bytes:
    n = 16000 * ms // 1000
    return struct.pack(f"<{n}h", *([0] * n))


