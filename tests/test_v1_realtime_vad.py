def test_vad_emits_started_and_stopped_on_real_audio() -> None:
    fixture = Path("/tmp/realtime_fixture.wav")
    if not fixture.exists():
        pytest.skip(
            "Fixture /tmp/realtime_fixture.wav not present "
            "(generated by GPU validation step)."
        )
    pcm = _read_wav_pcm16_16k(fixture)

    emits = emits_for_test(pcm, threshold=0.5, silence_duration_ms=400)
    types = [e[0] for e in emits]
    starts = sum(1 for t in types if t == VADEvent.SPEECH_STARTED)
    stops = sum(1 for t in types if t == VADEvent.SPEECH_STOPPED)
    assert starts >= 1, f"expected ≥1 speech_started, got: {emits}"
    assert stops >= 1, f"expected ≥1 speech_stopped, got: {emits}"
    # Each stop must be preceded by a start.
    seen_open = 0
    for t, _ in emits:
        if t == VADEvent.SPEECH_STARTED:
            seen_open += 1
        elif t == VADEvent.SPEECH_STOPPED:
            assert seen_open > 0
            seen_open -= 1


def test_vad_silent_audio_emits_nothing() -> None:
    pcm = _silence_pcm(2000)  # 2 s of silence
    emits = emits_for_test(pcm, threshold=0.5, silence_duration_ms=400)
    assert emits == [], f"silence should not trigger VAD, got {emits}"


def test_vad_reset_clears_state() -> None:
    vad = StreamingVAD(VADConfig(threshold=0.5, silence_duration_ms=400))
    vad._is_speech = True  # type: ignore[attr-defined]
    vad._silence_run_samples = 999  # type: ignore[attr-defined]
    vad._samples_consumed = 5000  # type: ignore[attr-defined]
    vad.reset()
    assert vad._is_speech is False  # type: ignore[attr-defined]
    assert vad._silence_run_samples == 0  # type: ignore[attr-defined]


def test_audio_buffer_slice_and_tail() -> None:
    buf = RealtimeAudioBuffer()
    raw = _silence_pcm(100)  # 1600 samples
    buf.append_b64(_b64(raw))

    # Tail returns the last N bytes
    last_400 = buf.tail(400)
    assert len(last_400) == 400
    # Slice (0, 200) returns a valid WAV
    uri = buf.slice_to_wav_data_uri(start_byte=0, end_byte=200)
    assert uri and uri.startswith("data:audio/wav;base64,")
    decoded = base64.b64decode(uri.split(",", 1)[1])
    assert decoded[:4] == b"RIFF"


