def _make_app(
    chunks_per_call: list[list[CompletionStreamChunk]],
) -> tuple[Any, FakeClient]:
    fake = FakeClient(chunks_per_call)
    app = create_app(fake, model_name="qwen3-omni-test", enable_realtime=True)
    return app, fake


def test_ws_session_update_enables_server_vad() -> None:
    app, _ = _make_app([])
    with TestClient(app) as client:
        with client.websocket_connect("/v1/realtime") as ws:
            assert ws.receive_json()["type"] == "session.created"
            ws.send_json(
                {
                    "type": "session.update",
                    "session": {
                        "modalities": ["text"],
                        "input_audio_format": "pcm16",
                        "turn_detection": {
                            "type": "server_vad",
                            "threshold": 0.5,
                            "silence_duration_ms": 400,
                        },
                    },
                }
            )
            evt = ws.receive_json()
            assert evt["type"] == "session.updated"


def test_ws_session_update_rejects_semantic_vad() -> None:
    app, _ = _make_app([])
    with TestClient(app) as client:
        with client.websocket_connect("/v1/realtime") as ws:
            ws.receive_json()  # session.created
            ws.send_json(
                {
                    "type": "session.update",
                    "session": {"turn_detection": {"type": "semantic_vad"}},
                }
            )
            evt = ws.receive_json()
            assert evt["type"] == "error"
            assert "semantic_vad" in evt["error"]["message"]


def test_ws_server_vad_auto_commits_speech_segment() -> None:
    fixture = Path("/tmp/realtime_fixture.wav")
    if not fixture.exists():
        pytest.skip("Fixture /tmp/realtime_fixture.wav not present")

    pcm = _read_wav_pcm16_16k(fixture)
    # Append a 1s silence trailer so VAD sees a clear speech_stopped.
    pcm_padded = pcm + _silence_pcm(1500)

    chunks = [
        CompletionStreamChunk(request_id="x", text="hello", modality="text"),
        CompletionStreamChunk(
            request_id="x", text="", modality="text", finish_reason="stop"
        ),
    ]
    app, fake = _make_app([chunks, chunks, chunks])
    with TestClient(app) as client:
        with client.websocket_connect("/v1/realtime") as ws:
            ws.receive_json()  # session.created
            ws.send_json(
                {
                    "type": "session.update",
                    "session": {
                        "modalities": ["text"],
                        "input_audio_format": "pcm16",
                        "turn_detection": {
                            "type": "server_vad",
                            "threshold": 0.5,
                            "silence_duration_ms": 400,
                            "prefix_padding_ms": 200,
                        },
                    },
                }
            )
            assert ws.receive_json()["type"] == "session.updated"

            # Stream the audio in 200 ms chunks (6400 bytes each).
            chunk_bytes = 6400
            for i in range(0, len(pcm_padded), chunk_bytes):
                ws.send_json(
                    {
                        "type": "input_audio_buffer.append",
                        "audio": _b64(pcm_padded[i : i + chunk_bytes]),
                    }
                )

            collected: list[dict] = []
            for _ in range(40):
                evt = ws.receive_json()
                collected.append(evt)
                if evt["type"] == "conversation.item.input_audio_transcription.completed":
                    break

    types = [e["type"] for e in collected]
    assert "input_audio_buffer.speech_started" in types, types
    assert "input_audio_buffer.speech_stopped" in types, types
    assert "input_audio_buffer.committed" in types, types
    assert "conversation.item.input_audio_transcription.completed" in types, types

    # The fake client should have been called with a data URI carrying
    # the speech segment (not the full buffer + trailing silence).
    audio_payload = fake.last_payloads[-1]
    assert audio_payload and isinstance(audio_payload[0], str)
    assert audio_payload[0].startswith("data:audio/wav;base64,")
